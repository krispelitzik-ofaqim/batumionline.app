type Ctx = { lang: Lang; setLang: (l: Lang) => void; toggle: () => void; t: (k: string) => string; isRTL: boolean };
const I18nCtx = createContext<Ctx>({ lang: 'he', setLang: () => {}, toggle: () => {}, t: (k) => k, isRTL: true });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('he');
  useEffect(() => {
    AsyncStorage.getItem('appLang').then(v => { if (v === 'en' || v === 'he' || v === 'fa' || v === 'ru') { setLangState(v); setContentLang(v); } }).catch(() => {});
  }, []);
  const setLang = (l: Lang) => { setLangState(l); setContentLang(l); AsyncStorage.setItem('appLang', l).catch(() => {}); };
  const toggle = () => setLang(lang === 'he' ? 'en' : lang === 'en' ? 'fa' : lang === 'fa' ? 'ru' : 'he');
  const t = (k: string) => {
    if (lang === 'fa') return FA[k] ?? STRINGS[k]?.en ?? STRINGS[k]?.he ?? k;
    if (lang === 'ru') return RU[k] ?? STRINGS[k]?.en ?? STRINGS[k]?.he ?? k;
    return STRINGS[k]?.[lang] ?? STRINGS[k]?.he ?? k;
  };
  return <I18nCtx.Provider value={{ lang, setLang, toggle, t, isRTL: lang === 'he' || lang === 'fa' }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
